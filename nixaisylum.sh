#!/usr/bin/env bash
# <https://gist.github.com/mohanpedala/1e2ff5661761d3abd0385e8223e16425>
set -euo pipefail

# ---------------------------------------------------------
# Globals
# ---------------------------------------------------------

VM=".nixaisylum-vm"
PID="$VM/vm.pid"
VFS_PID="$VM/virtiofsd.pid"
LOG="$VM/vm.log"
PORT_FILE="$VM/ssh-port"
NIX_DIR="@NIXAISYLUM_NIX_DIR@"
TEMPLATE_DIR="$NIX_DIR/templates"
# Project-local, git-tracked copies of the selected templates
MODULE_DIR="nixaisylum"
VERSION="@NIXAISYLUM_VERSION@"


# ---------------------------------------------------------
# Helpers SSH
# ---------------------------------------------------------

get_random_free_port() {
  local port
  while true; do
    # Below the kernel's ephemeral range (32768) to avoid collisions
    port=$(( 10000 + RANDOM % 22768 ))
    if ! (exec 3<>/dev/tcp/127.0.0.1/"$port") 2>/dev/null; then
      echo "$port"
      return 0
    fi
  done
}


# Use saved port if VM is initialized, otherwise generate a new one
if [[ -f "$PORT_FILE" ]]; then
  SSH_PORT=$(<"$PORT_FILE")
else
  SSH_PORT=$(get_random_free_port)
fi


SSH=(
  ssh
  # Keep host SSH configuration and unrelated agent keys out of VM connections.
  -F /dev/null
  -p "$SSH_PORT"
  -i "$VM/id_ed25519"
  -o IdentitiesOnly=yes
  # Avoid QoS marking on the local QEMU connection; throughput is deprecated.
  -o IPQoS=none
  -o TCPKeepAlive=yes
  -o "UserKnownHostsFile=$VM/known_hosts"
  -o StrictHostKeyChecking=yes
  -o LogLevel=ERROR
  -o ConnectTimeout=2
  -o BatchMode=yes
  user@127.0.0.1
)


# ---------------------------------------------------------
# Helpers VM
# ---------------------------------------------------------

is_running() {
  local pid
  [[ -f "$PID" ]] || return 1
  read -r pid < "$PID" || return 1
  [[ -n "$pid" ]] && kill -0 "$pid" 2>/dev/null
}


# Read a template's description from its leading '## ' comment line
template_desc() {
  local first
  IFS= read -r first < "$1" || true
  if [[ $first == '## '* ]]; then
    printf '%s' "${first#'## '}"
  else
    printf '%s' '(no description)'
  fi
}


# Every file that affects the build: the wrapper plus its modules
config_files() {
  printf '%s\n' nixaisylum.vm.nix
  [[ -d "$MODULE_DIR" ]] || return 0
  local f
  for f in "$MODULE_DIR"/*.nix; do
    [[ -f $f ]] && printf '%s\n' "$f"
  done
}


# Generate nixaisylum.vm.nix: imports the selected modules + VM-level options.
#  Keep VM options here, not in modules: NixOS cannot merge two scalar values,
#  so 'mem' defined by two modules at once would be a build error.
write_wrapper() {
  local m
  {
    echo "# Generated by 'nixaisylum init $*'"
    echo "# Edit freely, then run 'nixaisylum sync' to apply changes."
    echo "{ pkgs, ... }:"
    echo "{"
    echo "  imports = ["
    for m in "$@"; do
      echo "    ./$MODULE_DIR/$m.nix"
    done
    echo "  ];"
    echo
    echo "  #nixpkgs.config.allowUnfree = true;"
    echo
    echo
    echo "  #environment.systemPackages = with pkgs; [];"
    echo
    echo "  ## Adjust VM resources (defaults: 4 GB RAM, 4 vCPUs)"
    echo "  #microvm.mem = 4096;"
    echo "  #microvm.vcpu = 4;"
    echo
    echo "  ## Expose VM services on the host (optional)"
    echo "  #microvm.forwardPorts = ["
    echo "  #  { from = \"host\"; host.port = 5432; guest.port = 5432; }  # postgres"
    echo "  #  { from = \"host\"; host.port = 3900; guest.port = 3900; }  # garage s3"
    echo "  #];"
    echo
    echo "  ## Enable the native NixOS firewall inside the VM (disabled by default)"
    echo "  #networking.firewall.enable = true;"
    echo "  ## Ports must be opened here too, when the firewall is on"
    echo "  #networking.firewall.allowedTCPPorts = [ 5432 3900 ];"
    echo
    echo "  ## QEMU's user-mode network typically uses 10.0.2.0/24 with gateway 10.0.2.2"
    echo "  #networking.firewall.extraCommands = ''"
    echo "  #  # Whitelist specific egress endpoints"
    echo "  #  iptables -I OUTPUT -d 10.0.2.0/24 -j ACCEPT"
    echo "  #  # Block outbound connections to private network ranges (RFC 1918)"
    echo "  #  iptables -A OUTPUT -d 10.0.0.0/8 -j REJECT"
    echo "  #  iptables -A OUTPUT -d 172.16.0.0/12 -j REJECT"
    echo "  #  iptables -A OUTPUT -d 192.168.0.0/16 -j REJECT"
    echo "  #'';"
    echo
    echo "  ## Mount extra host paths"
    echo "  #microvm.shares = [{"
    echo "  #  tag = \"home-ssh\";"
    echo "  #  source = \"/home/user/in\";"
    echo "  #  mountPoint = \"/home/user/out\";"
    echo "  #  proto = \"virtiofs\";"
    echo "  #  readOnly = true; # Enforces read-only access for the microVM"
    echo "  #}];"
    echo "}"
  } > nixaisylum.vm.nix
  chmod 644 nixaisylum.vm.nix
}


stop_virtiofsd() {
  [[ -f "$VFS_PID" ]] || return 0
  kill "$(<"$VFS_PID")" 2>/dev/null || true
  rm -f "$VFS_PID"
}


# ---------------------------------------------------------
# Commands
# ---------------------------------------------------------

templates() {
  local f name
  echo "Available templates:"
  for f in "$TEMPLATE_DIR"/*.nix; do
    [[ -f $f ]] || continue
    name=${f##*/}
    printf '  %-12s %s\n' "${name%.nix}" "$(template_desc "$f")"
  done
}


init() {
  local src="$VM/source"
  local host_keys="$VM/ssh-host-keys"
  local -a modules=("$@")
  local m

  # Default to the minimal module
  [[ ${#modules[@]} -gt 0 ]] || modules=(minimal)

  # Validate every name up front, so we never write a partial config
  for m in "${modules[@]}"; do
    if [[ ! -f "$TEMPLATE_DIR/$m.nix" ]]; then
      echo "Error: unknown template '$m'" >&2
      echo "Run 'nixaisylum templates' to list available templates." >&2
      exit 1
    fi
  done

  # Prepare dir/file structure
  mkdir -p "$src" "$host_keys"
  install -m 644 "$NIX_DIR"/{flake.nix,flake.lock} "$src/"

  if [[ -e nixaisylum.vm.nix ]]; then
    echo "Warning: nixaisylum.vm.nix already exists, keeping existing configuration" >&2
    echo "         (remove it or run 'nixaisylum destroy' to re-initialize)" >&2
  else
    # Modules are tracked in the project so users can edit them and keep history
    mkdir -p "$MODULE_DIR"
    for m in "${modules[@]}"; do
      install -m 644 "$TEMPLATE_DIR/$m.nix" "$MODULE_DIR/$m.nix"
    done
    write_wrapper "${modules[@]}"
    echo "Initialized from: ${modules[*]}"
    echo "  nixaisylum.vm.nix   VM options (edit to enable firewall, forward ports)"
    echo "  $MODULE_DIR/    module files (edit to change packages)"
  fi

  # Store project metadata & fixed SSH port for this VM
  printf '%s' "$PWD" > "$src/project-root"
  printf '%s' 'x86_64-linux' > "$src/system"
  printf '%s' "$SSH_PORT" > "$PORT_FILE"
  printf '%s' "$SSH_PORT" > "$src/ssh-port"
  id -u > "$src/host-uid"
  id -g > "$src/host-gid"

  # Generate SSH credentials (client and VM host), reusing any existing keys
  [[ -f "$VM/id_ed25519" ]] || ssh-keygen -q -t ed25519 -N '' -f "$VM/id_ed25519"
  [[ -f "$host_keys/ssh_host_ed25519_key" ]] || ssh-keygen -q -t ed25519 -N '' -f "$host_keys/ssh_host_ed25519_key"
  cp "$VM/id_ed25519.pub" "$src/"

  # Register VM in known_hosts
  read -r key_type pub_key _ < "$host_keys/ssh_host_ed25519_key.pub"
  echo "[127.0.0.1]:$SSH_PORT $key_type $pub_key" > "$VM/known_hosts"

  # Git ignore (if not already present)
  grep -qxF '.nixaisylum-vm/' .gitignore 2>/dev/null || echo '.nixaisylum-vm/' >> .gitignore
}


build() {
  local src="$VM/source"
  mkdir -p "$src"

  # copy files
  install -m 644 "$NIX_DIR"/{flake.nix,flake.lock} "$src/"
  install -m 644 nixaisylum.vm.nix "$src/"
  install -m 644 "$VM/id_ed25519.pub" "$src/"

  # Modules must keep the same relative path as in the project, so the
  #  './nixaisylum/*.nix' imports in nixaisylum.vm.nix still resolve here
  # ${var:?} guards against ever expanding to 'rm -rf /'
  rm -rf "${src:?}/${MODULE_DIR:?}"
  if [[ -d "$MODULE_DIR" ]]; then
    mkdir -p "$src/$MODULE_DIR"
    install -m 644 "$MODULE_DIR"/*.nix "$src/$MODULE_DIR/"
  fi

  printf '%s' "$PWD" > "$src/project-root"
  printf '%s' 'x86_64-linux' > "$src/system"
  printf '%s' "$SSH_PORT" > "$src/ssh-port"
  id -u > "$src/host-uid"
  id -g > "$src/host-gid"

  nix build "path:$src#nixosConfigurations.vm.config.microvm.declaredRunner" --out-link "$VM/result"

  # Hash every config file: hashing only the wrapper would make 'sync'
  #  report "up to date" after a module edit
  config_files | xargs sha256sum > "$VM/build-hash"
}


start() {
  if is_running; then
    echo "VM is already running"
    return 0
  fi

  # clean old state artifacts
  rm -f "$PID" "$VM"/*.sock

  if [[ ! -e "$VM/result" ]]; then
    echo "Build artifact not found. Building VM first..."
    build
  fi

  # launch virtiofsd and VM
  #  virtiofsd use ralative paths
  (
    cd "$VM" || exit 1

    if [[ -x ./result/bin/virtiofsd-run ]]; then
      # supervisord's config has hardcoded `user=root`
      #  so it throws error on non-root runnig
      #  `id -un` sets user=%current_user% to avoid it
      nohup ./result/bin/virtiofsd-run -u "$(id -un)" </dev/null >virtiofsd.log 2>&1 &
      echo $! >virtiofsd.pid
      # wait for the sockets
      for _ in {1..50}; do
        for s in *-virtiofs-*.sock; do [[ -S $s ]] && break 2; done
        sleep 0.1
      done
    fi

    nohup ./result/bin/microvm-run </dev/null >vm.log 2>&1 &
    echo $! >vm.pid
  )

  local vm_pid
  read -r vm_pid < "$PID"
  local ssh_error="$VM/ssh.log"

  echo "Waiting for SSH..."
  for _ in {1..30}; do
    if "${SSH[@]}" true 2>"$ssh_error"; then
      echo "VM is ready"
      return 0
    fi

    if ! kill -0 "$vm_pid" 2>/dev/null; then
      stop_virtiofsd
      rm -f "$PID"
      echo "VM exited unexpectedly. Check $LOG and $VM/virtiofsd.log" >&2
      exit 1
    fi

    sleep 1
  done

  # Do not orphan qemu: it would keep holding the forwarded port
  kill "$vm_pid" 2>/dev/null || true
  stop_virtiofsd
  rm -f "$PID"
  echo "VM SSH readiness check failed. Last SSH error:" >&2
  cat "$ssh_error" >&2
  echo "Check $ssh_error, $LOG and $VM/virtiofsd.log" >&2
  exit 1
}


stop() {
  if ! is_running; then
    stop_virtiofsd
    rm -f "$PID"
    echo "VM is not running"
    return 0
  fi

  local pid
  pid=$(<"$PID")
  echo "Stopping VM..."

  # sudo: we log in as an unprivileged user (wheelNeedsPassword is false)
  "${SSH[@]}" 'sudo poweroff' 2>/dev/null || true

  for _ in {1..10}; do
    if ! kill -0 "$pid" 2>/dev/null; then
      break
    fi
    sleep 0.5
  done

  if kill -0 "$pid" 2>/dev/null; then
    kill "$pid" 2>/dev/null || true
  fi

  stop_virtiofsd
  rm -f "$PID" "$VM"/*.sock
  echo "VM stopped"
}


shell() {
  start
  ssh -t "${SSH[@]:1}" 'cd /workspace && exec bash -l'
}


sync() {
  # Compare the file list too: 'sha256sum -c' only checks files it knows about,
  #  so a newly added module would otherwise look like "up to date"
  if [[ -f "$VM/build-hash" ]] \
    && cmp -s "$NIX_DIR/flake.nix" "$VM/source/flake.nix" \
    && grep -qxF "$(id -u)" "$VM/source/host-uid" 2>/dev/null \
    && grep -qxF "$(id -g)" "$VM/source/host-gid" 2>/dev/null \
    && [[ "$(config_files)" == "$(awk '{ print $2 }' "$VM/build-hash")" ]] \
    && sha256sum -c "$VM/build-hash" >/dev/null 2>&1; then
    echo "VM is up to date"
    return 0
  fi

  if is_running; then
    stop
    build
    start
  else
    build
  fi
}


status() {
  if is_running; then
    echo "VM is running (PID: $(<"$PID"))."
  else
    rm -f "$PID"
    echo "VM is stopped"
  fi
}


destroy() {
  if is_running; then
    stop
  else
    stop_virtiofsd
  fi

  # $MODULE_DIR is git-tracked on purpose, so edits here are recoverable
  rm -rf "${VM:?}" nixaisylum.vm.nix "${MODULE_DIR:?}"
  echo "VM destroyed"
}


# ---------------------------------------------------------
# CLI Router
# ---------------------------------------------------------

usage() {
  echo "Usage: nixaisylum <command> [arguments]"
  echo
  echo "Commands:"
  echo "  init [TPL...]  Initialize VM from one or more templates (default: minimal)"
  echo "  templates   List available templates"
  echo "  build       Build the MicroVM runner with Nix"
  echo "  start       Start the VM in the background"
  echo "  stop        Gracefully stop the running VM"
  echo "  shell       Open an interactive shell in the VM"
  echo "  sync        Rebuild and reload if configuration changed"
  echo "  status      Check VM state and PID"
  echo "  destroy     Stop and delete all VM files"
  echo "  version     Show version information"
}


command="${1:-help}"
shift || true
case "$command" in
  init)
    init "$@"
    ;;

  templates)
    templates
    ;;

  destroy)
    destroy
    ;;

  build|start|stop|shell|sync|status)
    if [[ ! -f nixaisylum.vm.nix ]]; then
      echo "Error: Configuration file 'nixaisylum.vm.nix' not found." >&2
      echo "Run 'nixaisylum init' first." >&2
      exit 1
    fi
    "$command"
    ;;

  version|--version|-v)
    echo "nixaisylum $VERSION"
    ;;

  help|--help|-h)
    usage
    ;;

  *)
    echo "Error: Unknown command '$command'" >&2
    usage >&2
    exit 1
    ;;
esac
